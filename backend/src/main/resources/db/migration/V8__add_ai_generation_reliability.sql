ALTER TABLE post_analyses
	ADD COLUMN attempt_count INTEGER NOT NULL DEFAULT 0,
	ADD COLUMN next_attempt_at TIMESTAMPTZ,
	ADD COLUMN last_failure_code VARCHAR(50),
	ADD COLUMN last_failed_at TIMESTAMPTZ,
	ADD COLUMN input_updated_at TIMESTAMPTZ,
	ADD COLUMN claim_token UUID,
	ADD COLUMN claim_expires_at TIMESTAMPTZ,
	ADD CONSTRAINT ck_post_analysis_attempt_count
		CHECK (attempt_count BETWEEN 0 AND 3),
	ADD CONSTRAINT ck_post_analysis_claim
		CHECK (
			(claim_token IS NULL AND claim_expires_at IS NULL AND input_updated_at IS NULL)
			OR (claim_token IS NOT NULL AND claim_expires_at IS NOT NULL AND input_updated_at IS NOT NULL)
		);

UPDATE post_analyses
SET status = 'PENDING',
	summary = NULL,
	analyzed_at = NULL
WHERE status = 'FAILED';

CREATE INDEX idx_post_analyses_retry
	ON post_analyses (status, next_attempt_at, claim_expires_at);

CREATE TABLE daily_report_generation_claims (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	care_receiver_member_id BIGINT NOT NULL REFERENCES group_members (id) ON DELETE CASCADE,
	report_date DATE NOT NULL,
	claim_token UUID NOT NULL,
	claim_expires_at TIMESTAMPTZ NOT NULL,
	input_report_count INTEGER NOT NULL,
	input_latest_report_id BIGINT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_daily_report_generation_claims_member_date
		UNIQUE (care_receiver_member_id, report_date),
	CONSTRAINT ck_daily_report_generation_claims_input
		CHECK (input_report_count > 0 AND input_latest_report_id > 0)
);

CREATE INDEX idx_daily_report_generation_claims_expiry
	ON daily_report_generation_claims (claim_expires_at);
