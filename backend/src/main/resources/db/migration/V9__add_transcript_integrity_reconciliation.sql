CREATE TYPE transcript_integrity_status AS ENUM (
	'COLLECTING',
	'COMPLETE',
	'RECONCILIATION_REQUIRED'
);

CREATE TYPE transcript_ingest_status AS ENUM (
	'RESERVED',
	'READY',
	'APPLIED',
	'FAILED'
);

CREATE TYPE call_report_generation_status AS ENUM (
	'PENDING',
	'CLAIMED',
	'GEMINI_FAILED',
	'DONE'
);

ALTER TABLE call_sessions
	ADD COLUMN transcript_integrity_status transcript_integrity_status NOT NULL DEFAULT 'COLLECTING',
	ADD COLUMN transcript_revision BIGINT NOT NULL DEFAULT 0,
	ADD COLUMN transcript_finalized_at TIMESTAMPTZ,
	ADD CONSTRAINT ck_call_sessions_transcript_revision CHECK (transcript_revision >= 0);

UPDATE call_sessions session
SET transcript_revision = (
	SELECT COUNT(*)
	FROM call_transcripts transcript
	WHERE transcript.call_session_id = session.id
);

UPDATE call_sessions session
SET transcript_integrity_status = 'COMPLETE',
	transcript_finalized_at = COALESCE(session.ended_at, session.created_at)
WHERE session.status = 'COMPLETED'
	AND EXISTS (
		SELECT 1
		FROM call_reports report
		WHERE report.call_session_id = session.id
	);

UPDATE call_sessions session
SET transcript_integrity_status = 'RECONCILIATION_REQUIRED',
	transcript_finalized_at = NULL
WHERE session.status = 'INCOMPLETE'
	OR (
		session.status = 'COMPLETED'
		AND NOT EXISTS (
			SELECT 1
			FROM call_reports report
			WHERE report.call_session_id = session.id
		)
	);

UPDATE call_sessions
SET transcript_integrity_status = 'COMPLETE',
	transcript_finalized_at = COALESCE(ended_at, created_at)
WHERE status IN ('CANCELLED', 'FAILED');

CREATE TABLE call_transcript_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	call_session_id BIGINT NOT NULL REFERENCES call_sessions (id) ON DELETE CASCADE,
	openai_item_id VARCHAR(100) NOT NULL,
	speaker speaker_type NOT NULL,
	sequence INTEGER NOT NULL,
	status transcript_ingest_status NOT NULL,
	attempt_count INTEGER NOT NULL DEFAULT 0,
	content TEXT,
	content_hash VARCHAR(64),
	next_attempt_at TIMESTAMPTZ,
	claim_token UUID,
	claim_expires_at TIMESTAMPTZ,
	failure_code VARCHAR(80),
	ready_at TIMESTAMPTZ,
	applied_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_call_transcript_events_session_item
		UNIQUE (call_session_id, openai_item_id),
	CONSTRAINT uq_call_transcript_events_session_sequence
		UNIQUE (call_session_id, sequence),
	CONSTRAINT ck_call_transcript_events_sequence CHECK (sequence > 0),
	CONSTRAINT ck_call_transcript_events_attempt_count CHECK (attempt_count BETWEEN 0 AND 3),
	CONSTRAINT ck_call_transcript_events_claim CHECK (
		(claim_token IS NULL AND claim_expires_at IS NULL)
		OR (claim_token IS NOT NULL AND claim_expires_at IS NOT NULL)
	),
	CONSTRAINT ck_call_transcript_events_payload CHECK (
		(status = 'RESERVED' AND content IS NULL AND content_hash IS NULL)
		OR (status = 'READY' AND content IS NOT NULL AND content_hash IS NOT NULL AND ready_at IS NOT NULL)
		OR (status = 'APPLIED' AND content IS NULL AND content_hash IS NOT NULL AND applied_at IS NOT NULL)
		OR status = 'FAILED'
	)
);

CREATE INDEX idx_call_transcript_events_retry
	ON call_transcript_events (status, next_attempt_at, claim_expires_at, id)
	WHERE status = 'READY';

CREATE INDEX idx_call_transcript_events_session_status
	ON call_transcript_events (call_session_id, status);

CREATE INDEX idx_call_transcript_events_cleanup
	ON call_transcript_events (status, created_at, id)
	WHERE status IN ('READY', 'FAILED');

CREATE UNIQUE INDEX uq_call_transcripts_session_item
	ON call_transcripts (call_session_id, openai_item_id)
	WHERE openai_item_id IS NOT NULL;

CREATE TABLE call_report_generation_requests (
	call_session_id BIGINT PRIMARY KEY REFERENCES call_sessions (id) ON DELETE CASCADE,
	status call_report_generation_status NOT NULL DEFAULT 'PENDING',
	input_revision BIGINT NOT NULL,
	claim_token UUID,
	claim_expires_at TIMESTAMPTZ,
	last_failure_code VARCHAR(50),
	last_failed_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT ck_call_report_generation_input_revision CHECK (input_revision >= 0),
	CONSTRAINT ck_call_report_generation_claim CHECK (
		(status = 'CLAIMED' AND claim_token IS NOT NULL AND claim_expires_at IS NOT NULL)
		OR (status <> 'CLAIMED' AND claim_token IS NULL AND claim_expires_at IS NULL)
	),
	CONSTRAINT ck_call_report_generation_failure CHECK (
		(status = 'GEMINI_FAILED' AND last_failure_code IS NOT NULL AND last_failed_at IS NOT NULL)
		OR status <> 'GEMINI_FAILED'
	)
);

CREATE INDEX idx_call_report_generation_requests_recovery
	ON call_report_generation_requests (status, claim_expires_at, created_at, call_session_id);

CREATE FUNCTION enforce_call_report_transcript_integrity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
	session_status call_status;
	integrity_status transcript_integrity_status;
	finalized_at TIMESTAMPTZ;
BEGIN
	SELECT status, transcript_integrity_status, transcript_finalized_at
	INTO session_status, integrity_status, finalized_at
	FROM call_sessions
	WHERE id = NEW.call_session_id
	FOR UPDATE;

	IF session_status NOT IN ('COMPLETED', 'INCOMPLETE')
		OR integrity_status <> 'COMPLETE'
		OR finalized_at IS NULL
		OR EXISTS (
			SELECT 1
			FROM call_transcript_events event
			WHERE event.call_session_id = NEW.call_session_id
				AND event.status <> 'APPLIED'
		) THEN
		RAISE EXCEPTION 'call report requires a finalized complete transcript'
			USING ERRCODE = '23514';
	END IF;

	RETURN NEW;
END;
$$;

CREATE TRIGGER trg_call_reports_transcript_integrity
	BEFORE INSERT OR UPDATE ON call_reports
	FOR EACH ROW
	EXECUTE FUNCTION enforce_call_report_transcript_integrity();
