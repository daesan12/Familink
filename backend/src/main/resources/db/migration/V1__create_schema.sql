CREATE TYPE user_gender AS ENUM ('MALE', 'FEMALE');
CREATE TYPE group_role AS ENUM ('GUARDIAN', 'CARE_RECEIVER');
CREATE TYPE join_request_status AS ENUM ('PENDING_ADMIN', 'APPROVED', 'REJECTED');
CREATE TYPE media_type AS ENUM ('IMAGE', 'VIDEO');
CREATE TYPE reaction_type AS ENUM ('HEART', 'LAUGH', 'SURPRISE', 'SAD', 'SUPPORT');
CREATE TYPE analysis_status AS ENUM ('PENDING', 'SUCCESS', 'FAILED');
CREATE TYPE notification_type AS ENUM (
	'NEW_POST',
	'POST_ACTIVITY',
	'EVENT_CHANGED',
	'EVENT_REMINDER',
	'CALL_REPORT',
	'DAILY_REPORT',
	'GROUP_JOIN_REQUEST'
);
CREATE TYPE call_status AS ENUM (
	'CONNECTING',
	'IN_PROGRESS',
	'COMPLETED',
	'INCOMPLETE',
	'CANCELLED',
	'FAILED'
);
CREATE TYPE speaker_type AS ENUM ('USER', 'ASSISTANT');
CREATE TYPE emotion_category AS ENUM (
	'ANGER',
	'SADNESS',
	'ANXIETY',
	'HURT',
	'EMBARRASSMENT',
	'JOY',
	'NEUTRAL'
);

CREATE TABLE users (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	login_id VARCHAR(15) UNIQUE,
	password_hash VARCHAR(255),
	name VARCHAR(10),
	birth_date DATE,
	gender user_gender,
	profile_image_url VARCHAR(500),
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	withdrawn_at TIMESTAMPTZ
);

CREATE TABLE family_groups (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(10) NOT NULL,
	invite_code VARCHAR(6) NOT NULL UNIQUE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE group_members (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	user_id BIGINT NOT NULL REFERENCES users (id),
	role group_role NOT NULL,
	is_manager BOOLEAN NOT NULL DEFAULT FALSE,
	joined_at TIMESTAMPTZ NOT NULL,
	left_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_group_members_group_user UNIQUE (group_id, user_id)
);
CREATE UNIQUE INDEX uq_group_active_manager
	ON group_members (group_id)
	WHERE is_manager = TRUE AND left_at IS NULL;
CREATE UNIQUE INDEX uq_user_active_care_receiver
	ON group_members (user_id)
	WHERE role = 'CARE_RECEIVER' AND left_at IS NULL;
CREATE INDEX idx_group_members_active_group
	ON group_members (group_id, left_at);

CREATE TABLE group_join_requests (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	applicant_user_id BIGINT NOT NULL REFERENCES users (id),
	assigned_role group_role,
	status join_request_status NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	processed_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_pending_group_join_request
	ON group_join_requests (group_id, applicant_user_id)
	WHERE status = 'PENDING_ADMIN';

CREATE TABLE member_aliases (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	owner_member_id BIGINT NOT NULL REFERENCES group_members (id),
	target_member_id BIGINT NOT NULL REFERENCES group_members (id),
	alias VARCHAR(10) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_member_aliases_members UNIQUE (group_id, owner_member_id, target_member_id),
	CONSTRAINT ck_member_aliases_distinct_members CHECK (owner_member_id <> target_member_id)
);

CREATE TABLE member_interests (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	care_receiver_member_id BIGINT NOT NULL REFERENCES group_members (id),
	interest_text VARCHAR(10) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_member_interests_member_text UNIQUE (care_receiver_member_id, interest_text)
);

CREATE TABLE posts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	author_member_id BIGINT NOT NULL REFERENCES group_members (id),
	content VARCHAR(140) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_posts_group_created_at ON posts (group_id, created_at DESC);

CREATE TABLE post_media (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	post_id BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
	media_type media_type NOT NULL,
	file_url VARCHAR(500) NOT NULL,
	display_order INTEGER NOT NULL,
	thumbnail_url VARCHAR(500),
	CONSTRAINT uq_post_media_display_order UNIQUE (post_id, display_order),
	CONSTRAINT ck_post_media_display_order_non_negative CHECK (display_order >= 0)
);

CREATE TABLE comments (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	post_id BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
	author_member_id BIGINT NOT NULL REFERENCES group_members (id),
	content VARCHAR(50) NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_comments_post_created_at ON comments (post_id, created_at);

CREATE TABLE post_reactions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	post_id BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
	group_member_id BIGINT NOT NULL REFERENCES group_members (id),
	reaction_type reaction_type NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_post_reactions_post_member UNIQUE (post_id, group_member_id)
);

CREATE TABLE post_analyses (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	post_id BIGINT NOT NULL UNIQUE REFERENCES posts (id) ON DELETE CASCADE,
	status analysis_status NOT NULL,
	summary VARCHAR(500),
	analyzed_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT ck_post_analysis_result CHECK (
		(status = 'SUCCESS' AND summary IS NOT NULL AND analyzed_at IS NOT NULL)
		OR (status IN ('PENDING', 'FAILED') AND summary IS NULL AND analyzed_at IS NULL)
	)
);

CREATE TABLE calendar_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	creator_member_id BIGINT NOT NULL REFERENCES group_members (id),
	last_editor_member_id BIGINT NOT NULL REFERENCES group_members (id),
	title VARCHAR(20) NOT NULL,
	description VARCHAR(50),
	event_date DATE NOT NULL,
	start_at TIME,
	end_at TIME,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT ck_calendar_event_time_range CHECK (
		(start_at IS NULL AND end_at IS NULL)
		OR (start_at IS NOT NULL AND end_at IS NOT NULL AND end_at >= start_at)
	)
);
CREATE INDEX idx_calendar_events_group_date ON calendar_events (group_id, event_date);

CREATE TABLE event_participants (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id BIGINT NOT NULL REFERENCES calendar_events (id) ON DELETE CASCADE,
	group_member_id BIGINT NOT NULL REFERENCES group_members (id),
	CONSTRAINT uq_event_participants_event_member UNIQUE (event_id, group_member_id)
);

CREATE TABLE call_sessions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	care_receiver_member_id BIGINT NOT NULL REFERENCES group_members (id),
	persona_id BIGINT NOT NULL,
	status call_status NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	started_at TIMESTAMPTZ,
	ended_at TIMESTAMPTZ
);
CREATE INDEX idx_call_sessions_group_created_at ON call_sessions (group_id, created_at DESC);

CREATE TABLE call_transcripts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	call_session_id BIGINT NOT NULL REFERENCES call_sessions (id) ON DELETE CASCADE,
	speaker speaker_type NOT NULL,
	content TEXT NOT NULL,
	sequence INTEGER NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	openai_item_id VARCHAR(100),
	CONSTRAINT uq_call_transcripts_session_sequence UNIQUE (call_session_id, sequence)
);
CREATE INDEX idx_call_transcripts_session_sequence ON call_transcripts (call_session_id, sequence);

CREATE TABLE call_reports (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	call_session_id BIGINT NOT NULL UNIQUE REFERENCES call_sessions (id) ON DELETE CASCADE,
	summary VARCHAR(100) NOT NULL,
	emotion_category emotion_category NOT NULL,
	emotion_subcategory VARCHAR(50) NOT NULL,
	guardian_message VARCHAR(100),
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE daily_reports (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	care_receiver_member_id BIGINT NOT NULL REFERENCES group_members (id),
	report_date DATE NOT NULL,
	summary VARCHAR(200) NOT NULL,
	emotion_category emotion_category NOT NULL,
	emotion_subcategory VARCHAR(50) NOT NULL,
	guardian_message VARCHAR(200),
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_daily_reports_member_date UNIQUE (care_receiver_member_id, report_date)
);
CREATE INDEX idx_daily_reports_group_date ON daily_reports (group_id, report_date);

CREATE TABLE carnations (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	group_id BIGINT NOT NULL REFERENCES family_groups (id),
	group_member_id BIGINT NOT NULL REFERENCES group_members (id),
	earned_date DATE NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_carnations_member_date UNIQUE (group_member_id, earned_date)
);
CREATE INDEX idx_carnations_group_date ON carnations (group_id, earned_date);

CREATE TABLE notifications (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	receiver_user_id BIGINT NOT NULL REFERENCES users (id),
	actor_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
	group_id BIGINT REFERENCES family_groups (id) ON DELETE SET NULL,
	related_join_request_id BIGINT REFERENCES group_join_requests (id) ON DELETE SET NULL,
	related_post_id BIGINT REFERENCES posts (id) ON DELETE SET NULL,
	related_event_id BIGINT REFERENCES calendar_events (id) ON DELETE SET NULL,
	related_call_report_id BIGINT REFERENCES call_reports (id) ON DELETE SET NULL,
	related_daily_report_id BIGINT REFERENCES daily_reports (id) ON DELETE SET NULL,
	type notification_type NOT NULL,
	title TEXT NOT NULL,
	body TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	read_at TIMESTAMPTZ
);
CREATE INDEX idx_notifications_receiver_created_at ON notifications (receiver_user_id, created_at DESC);
CREATE UNIQUE INDEX uq_event_reminder_notification
	ON notifications (receiver_user_id, related_event_id, type)
	WHERE type = 'EVENT_REMINDER' AND related_event_id IS NOT NULL;

CREATE TABLE notification_settings (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users (id),
	notification_type notification_type NOT NULL,
	is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT uq_notification_settings_user_type UNIQUE (user_id, notification_type)
);

CREATE TABLE device_tokens (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users (id),
	token VARCHAR(500) NOT NULL UNIQUE,
	device_type VARCHAR(20) NOT NULL,
	is_active BOOLEAN NOT NULL DEFAULT TRUE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_device_tokens_user_active ON device_tokens (user_id, is_active);
